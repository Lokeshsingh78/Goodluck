-- PRODUCTION-SAFE ATOMIC TRANSACTION & WEBHOOK IDEMPOTENCY RPC FUNCTION
CREATE OR REPLACE FUNCTION fulfill_order_payment_atomic(
  p_order_id TEXT,
  p_cashfree_order_id TEXT,
  p_cashfree_payment_id TEXT,
  p_cashfree_signature TEXT
) RETURNS JSONB AS $$
DECLARE
  v_current_payment_status TEXT;
  item RECORD;
BEGIN
  -- 1. Row Lock: Acquire row lock on target order to prevent concurrent execution races
  SELECT payment_status
  INTO v_current_payment_status
  FROM orders
  WHERE id = p_order_id
  FOR UPDATE;

  -- Exit if order record does not exist
  IF NOT FOUND THEN
    RETURN jsonb_build_object('success', false, 'already_processed', false, 'message', 'Order not found');
  END IF;

  -- 2. Idempotency Check A: If order is already paid, do not re-process or re-deduct stock
  IF v_current_payment_status = 'paid' THEN
    RETURN jsonb_build_object(
      'success', true, 
      'already_processed', true, 
      'message', 'Order is already marked as paid. Stock deduction skipped.'
    );
  END IF;

  -- 3. Idempotency Check B: If this exact cashfree_payment_id was already captured in payments table
  IF p_cashfree_payment_id IS NOT NULL AND EXISTS (
    SELECT 1 FROM payments 
    WHERE cashfree_payment_id = p_cashfree_payment_id AND status = 'captured'
  ) THEN
    UPDATE orders 
    SET payment_status = 'paid', 
        status = 'processing', 
        cashfree_payment_id = p_cashfree_payment_id
    WHERE id = p_order_id;

    RETURN jsonb_build_object(
      'success', true, 
      'already_processed', true, 
      'message', 'Cashfree payment ID already captured. Stock deduction skipped.'
    );
  END IF;

  -- 4. Update order payment status to paid
  UPDATE orders 
  SET payment_status = 'paid',
      status = 'processing',
      cashfree_order_id = COALESCE(p_cashfree_order_id, cashfree_order_id),
      cashfree_payment_id = COALESCE(p_cashfree_payment_id, cashfree_payment_id)
  WHERE id = p_order_id;

  -- 5. Upsert Payment Record (Update existing draft payment or insert captured record)
  IF EXISTS (SELECT 1 FROM payments WHERE order_id = p_order_id OR (p_cashfree_order_id IS NOT NULL AND cashfree_order_id = p_cashfree_order_id)) THEN
    UPDATE payments
    SET status = 'captured',
        cashfree_payment_id = COALESCE(p_cashfree_payment_id, cashfree_payment_id),
        cashfree_signature = COALESCE(p_cashfree_signature, cashfree_signature)
    WHERE order_id = p_order_id OR (p_cashfree_order_id IS NOT NULL AND cashfree_order_id = p_cashfree_order_id);
  ELSE
    INSERT INTO payments (order_id, cashfree_order_id, cashfree_payment_id, cashfree_signature, amount, status)
    SELECT id, COALESCE(p_cashfree_order_id, cashfree_order_id, 'N/A'), p_cashfree_payment_id, p_cashfree_signature, final_amount, 'captured'
    FROM orders WHERE id = p_order_id;
  END IF;

  -- 6. Atomic Stock Deduction (Executes exactly ONCE per unique order payment)
  FOR item IN SELECT product_id, quantity FROM order_items WHERE order_id = p_order_id LOOP
    UPDATE products 
    SET stock = GREATEST(0, stock - item.quantity),
        in_stock = (GREATEST(0, stock - item.quantity) > 0)
    WHERE id = item.product_id;
  END LOOP;

  RETURN jsonb_build_object(
    'success', true,
    'already_processed', false,
    'message', 'Order payment fulfilled and stock updated atomically.'
  );
END;
$$ LANGUAGE plpgsql;

-- PRODUCTION-SAFE SEQUENCE RESET RPC FUNCTION
CREATE OR REPLACE FUNCTION reset_identity_sequences() RETURNS JSONB AS $$
BEGIN
  PERFORM setval(pg_get_serial_sequence('users', 'id'), COALESCE((SELECT MAX(id) FROM users), 1));
  PERFORM setval(pg_get_serial_sequence('categories', 'id'), COALESCE((SELECT MAX(id) FROM categories), 1));
  PERFORM setval(pg_get_serial_sequence('order_items', 'id'), COALESCE((SELECT MAX(id) FROM order_items), 1));
  PERFORM setval(pg_get_serial_sequence('payments', 'id'), COALESCE((SELECT MAX(id) FROM payments), 1));
  PERFORM setval(pg_get_serial_sequence('cart_items', 'id'), COALESCE((SELECT MAX(id) FROM cart_items), 1));
  PERFORM setval(pg_get_serial_sequence('user_addresses', 'id'), COALESCE((SELECT MAX(id) FROM user_addresses), 1));
  PERFORM setval(pg_get_serial_sequence('coupons', 'id'), COALESCE((SELECT MAX(id) FROM coupons), 1));
  PERFORM setval(pg_get_serial_sequence('audit_logs', 'id'), COALESCE((SELECT MAX(id) FROM audit_logs), 1));
  PERFORM setval(pg_get_serial_sequence('wishlist', 'id'), COALESCE((SELECT MAX(id) FROM wishlist), 1));
  
  RETURN jsonb_build_object('success', true, 'message', 'All identity sequences reset to max(id) successfully.');
END;
$$ LANGUAGE plpgsql;
